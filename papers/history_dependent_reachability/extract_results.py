"""Extract every number the manuscript cites from the FROZEN results JSONs.

Read-only over Experiments/. Regenerates RESULTS_NUMBERS.md. If a number is not in
this file, the manuscript may not cite it. Run from this directory:
    python3 extract_results.py
"""
from __future__ import annotations
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent.parent / "Experiments"

def load(rel):
    return json.load(open(EXP / rel))

def fmt(x, nd=3):
    return f"{x:.{nd}f}"

out = []
out.append("# RESULTS NUMBERS — extracted from frozen JSONs\n")
out.append("Generated by `extract_results.py` (read-only over `Experiments/`). "
           "Manuscript numbers must come from this file.\n")

# ---------------- Phase 1 ----------------
d1 = load("anchoring_double_well/results_dissociation.json")
res = d1["results"]
out.append("\n## Phase 1 — plastic double-well (results_dissociation.json, "
           f"config_sha256={d1['config_sha256']})\n")
out.append("| condition | S@tau | P_survival | P_after_withdraw | W_sel(occ) | Wg_KL(uni) | J_ext | J_write |")
out.append("|---|---|---|---|---|---|---|---|")
for name, r in res.items():
    out.append(f"| {name} | {fmt(r['S_occ_tau'],2)} | {fmt(r['P_survival'])}±{fmt(r['P_survival_sd'])} "
               f"| {fmt(r['P_after_withdraw'])} | {fmt(r['Wsel']['occupancy'])} "
               f"| {fmt(r['Wglobal']['uniform']['KL'])} | {fmt(r['J_ext'],1)} | {fmt(r['J_write'],2)} |")
rw = res["RoughenWrite"]["Wglobal"]["uniform"]
out.append(f"\nRoughenWrite W_global (uniform ref): KL={fmt(rw['KL'],2)} JS={fmt(rw['JS'])} TV={fmt(rw['TV'])}")
li = res["LatentInscription"]
out.append(f"LatentInscription W_sel detail: occ={fmt(li['Wsel']['occupancy'])} "
           f"barrier={fmt(li['Wsel']['escape_barrier'])} committor={fmt(li['Wsel']['committor0'])}; "
           f"z_episode(h+)={fmt(li['z_after_int_hp'],2)}")
ca = res["C_anchor"]
out.append(f"C_anchor W_sel: occ={fmt(ca['Wsel']['occupancy'])} barrier={fmt(ca['Wsel']['escape_barrier'])} "
           f"committor={fmt(ca['Wsel']['committor0'])}")

mf = load("anchoring_double_well/results_matched_future.json")
out.append(f"\nMatched-present -> different-future: present gap={fmt(mf['present_state_gap'],4)}; "
           f"raw future P(M+): anchor={fmt(mf['raw_future_Pplus']['anchor'])} "
           f"naive={fmt(mf['raw_future_Pplus']['naive'])}; reachable anchor={mf['reachable']['anchor']} "
           f"naive={mf['reachable']['naive']}; KL={fmt(mf['divergences']['KL'],1)} "
           f"JS={fmt(mf['divergences']['JS'])} TV={fmt(mf['divergences']['TV'])}")

sw = load("anchoring_double_well/results_sweep.json")
out.append(f"Phase diagrams largest contiguous regions: anchor(P+Wsel+)={sw['anchor']['largest_region']['11']}, "
           f"latent(P-Wsel+)={sw['latent']['largest_region']['01']} "
           f"(grids {len(sw['anchor']['etas'])}x{len(sw['anchor']['D0s'])})")

# ---------------- Phase 2 ----------------
f2 = load("anchoring_bandit_feasibility/results_feasibility.json")
g1, g3, g4, g5 = f2["G1_z_separation"], f2["G3_durability"], f2["G4_future_divergence"], f2["G5_causal"]
out.append("\n## Phase 2 — bandit feasibility (results_feasibility.json)\n")
out.append(f"G1 z separation: vol={fmt(g1['z_vol_mean'])}±{fmt(g1['z_vol_sd'])} "
           f"stable={fmt(g1['z_stable_mean'])}±{fmt(g1['z_stable_sd'])} gap={fmt(g1['gap'])} d={fmt(g1['cohen_d'],2)}")
out.append(f"G3 durability: gap {fmt(g3['gap_after_formation'])} -> {fmt(g3['gap_after_washout'])} "
           f"retained={fmt(g3['retained_fraction']*100,0)}%")
out.append(f"G4 future (z frozen): early recovery vol={fmt(g4['early_recovery_vol'])} "
           f"stable={fmt(g4['early_recovery_stable'])} d={fmt(g4['cohen_d'],2)} "
           f"signs={g4['sign_stable_across_5_subseeds']}")
out.append(f"G5: null={g5['null_diff']:+.3f} swap={g5['swap_diff']:+.3f} "
           f"dose_spearman={fmt(g5['dose_spearman'],2)} random_ctrl={g5['random_control_diff']:+.3f}")
out.append(f"Calibrated gate (post-formation): zc={fmt(f2['calibrated_gate']['zc'],4)} "
           f"kk={fmt(f2['calibrated_gate']['kk'],4)}")

# ---------------- Phase 2b ----------------
b = load("anchoring_bandit_holdout/results_phase2b.json")
h, av, pm = b["holdout"], b["active_vs_yoked"], b["permutation"]
out.append("\n## Phase 2b — locked holdout NO-GO (results_phase2b.json; frozen from "
           f"feasibility commit {b['feasibility_commit'][:8]})\n")
out.append(f"Holdout n_seeds={h['n_seeds']}: retained={fmt(h['retained_mean']*100,0)}% "
           f"(min {fmt(h['retained_min']*100,0)}%); fut_diff={fmt(h['fut_diff_mean'])}±{fmt(h['fut_diff_sd'])} "
           f"(positive {fmt(h['fut_diff_positive_frac']*100,0)}%); null|.|={fmt(h['null_abs_mean'])}; "
           f"swap<0 {fmt(h['swap_negative_frac']*100,0)}%")
out.append(f"ACTIVE vs YOKED (selection-specificity FAIL): future effect active={fmt(av['fut_active_mean'])} "
           f"yoked={fmt(av['fut_yoked_mean'])} d={fmt(av['fut_cohen_d_active_vs_yoked'],2)}; "
           f"z-gap active={fmt(av['gap_active_mean'])} yoked={fmt(av['gap_yoked_mean'])} "
           f"ratio={fmt(av['gap_ratio'],2)}; stable-z active={fmt(av['stable_z_active_mean'])} "
           f"yoked={fmt(av['stable_z_yoked_mean'])}")
wc = b["washout_curves"]
out.append(f"Washout curves (steps {wc['wash_steps']}): retained={[round(x,2) for x in wc['retained']]}; "
           f"fut_diff={[round(x,3) for x in wc['fut_diff']]}")
out.append(f"Permutation: recovery~z(perm)={fmt(pm['corr_perm_recovery_vs_permz'])}; "
           f"recovery~label(perm)={fmt(pm['corr_perm_recovery_vs_label'])}")

# ---------------- Phase 2c ----------------
c = load("anchoring_2c_controllability/results_2c_holdout.json")
out.append("\n## Phase 2c — controllability holdout GO (results_2c_holdout.json)\n")
p, n = c["primary_ctrl"], c["negative_pe"]
out.append(f"PRIMARY (ctrl): paired active-yoked commitment mean={fmt(p['mean'])} "
           f"90%CI=[{fmt(p['ci_lo'])},{fmt(p['ci_hi'])}] vs Delta_min={p['Delta_min']}")
out.append(f"NEGATIVE (|PE|): mean={fmt(n['mean'])} 90%CI=[{fmt(n['ci_lo'])},{fmt(n['ci_hi'])}] "
           f"equivalence bound=±{n['eps']}  (pre-registered equivalence test WITHIN the 2c framework)")
for v in ("high", "low"):
    out.append(f"  vol={v}: d_ctrl={fmt(c['per_vol'][v]['d_ctrl'])} d_pe={fmt(c['per_vol'][v]['d_pe'])}; "
               f"z-formation ctrl(a-y)={fmt(c['z_formation'][v]['ctrl_active_minus_yoked'])} "
               f"pe(a-y)={c['z_formation'][v]['pe_active_minus_yoked']:+.3f}")
out.append(f"Manipulation: yoked ctrl-corr={c['manip']['ctrl_corr_yoked']:+.3f} "
           f"active={c['manip']['ctrl_corr_active']:+.3f}")
out.append(f"C_mu structural: active={fmt(c['Cmu']['active'])} yoked={fmt(c['Cmu']['yoked'])}")
cc = c["causal"]
out.append(f"Pipeline validation: null-z active commit {fmt(cc['active_normal_commit'])} -> "
           f"{fmt(cc['null_active_commit'])}; swap gap={cc['swap_gap']:+.3f} "
           f"(vs yoked {fmt(cc['yoked_commit'])})")
out.append(f"Bootstrap unit: seed x volatility (80 values, 2 per seed) — DISCLOSED LIMITATION")

# ---------------- tiny-MDP ----------------
m = load("anchoring_tiny_mdp_confirmatory/results_mdp_holdout.json")
out.append("\n## tiny-MDP confirmatory GO (results_mdp_holdout.json)\n")
pm2 = m["primary_macro_TV"]
out.append(f"PRIMARY: macro-TV mean={fmt(pm2['mean'])} 95%CI=[{fmt(pm2['ci'][0])},{fmt(pm2['ci'][1])}] "
           f"vs Delta_min={pm2['Delta_min']}; seeds n={len(m['seeds'])} "
           f"[{min(m['seeds'])}-{max(m['seeds'])}]; bootstrap={m['locked_thresholds']['bootstrap_resamples']}")
dr = m["direction"]
out.append(f"DIRECTION aligned advantage: {dr['aligned_active_adv'][0]:+.3f} "
           f"CI=[{dr['aligned_active_adv'][1]:+.3f},{dr['aligned_active_adv'][2]:+.3f}]")
out.append(f"DIRECTION blocked stickiness P(empty): {dr['blocked_active_stickiness'][0]:+.3f} "
           f"CI=[{dr['blocked_active_stickiness'][1]:+.3f},{dr['blocked_active_stickiness'][2]:+.3f}]")
out.append(f"DIRECTION novel restriction P(G_novel): {dr['novel_active_stickiness'][0]:+.3f} "
           f"CI=[{dr['novel_active_stickiness'][1]:+.3f},{dr['novel_active_stickiness'][2]:+.3f}]")
mn, ms, sz = m["memory_null_macroTV"], m["memory_swap_macroTV"], m["same_m_diff_z_macroTV"]
out.append(f"PIPELINE VALIDATION: memory-null={fmt(mn[0])} CI=[{fmt(mn[1])},{fmt(mn[2])}]; "
           f"memory-swap={fmt(ms[0])}; same-m/diff-z={fmt(sz[0])} (eps_TV=±{m['locked_thresholds']['eps_TV']})")
out.append(f"Sham mechanism gate: self={m['sham']['self_attr']:+.3f} ext={m['sham']['ext_attr']:+.3f}; "
           f"yoked ctrl-corr={m['yoked_ctrl_corr']:+.3f}")
out.append(f"Failures: {m['failures'] if m['failures'] else 'NONE'}")

(HERE / "RESULTS_NUMBERS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote RESULTS_NUMBERS.md ({len(out)} lines)")
